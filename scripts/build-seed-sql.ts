/**
 * Writes supabase/seed.sql from the JSON reference data, so the database matches /data.
 * Run after editing occupations or importing new JSA projections:  npm run db:seed-sql
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { jsaOutlook, occupationData } from "../src/lib/data.ts";

const q = (v: unknown) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v: unknown) => (typeof v === "number" && Number.isFinite(v) ? String(v) : "null");

export function buildSeedSql(): string {
  const occ = occupationData.occupations.map(
    (o) => `  (${q(o.id)}, ${q(o.anzsco)}, ${q(o.title)}, ${q(o.riasec)}, ${q(JSON.stringify(o))}::jsonb)`,
  );
  const source = `${jsaOutlook.source.title} (retrieved ${jsaOutlook.source.retrieved})`;
  const outlook = Object.entries(jsaOutlook.occupations).map(
    ([code, f]) => `  (${q(code)}, ${q(f.name)}, ${n(f.growth5Pct)}, ${n(f.growth10Pct)}, ${n(f.employed2025k)}, ${q(source)})`,
  );
  return [
    "-- Generated by scripts/build-seed-sql.ts. Do not edit by hand.",
    "begin;",
    "",
    "insert into public.occupations (id, anzsco, title, riasec, data) values",
    occ.join(",\n"),
    "on conflict (id) do update set anzsco = excluded.anzsco, title = excluded.title, riasec = excluded.riasec, data = excluded.data, updated_at = now();",
    "",
    "insert into public.occupation_outlook (anzsco, name, growth5_pct, growth10_pct, employed_2025k, source) values",
    outlook.join(",\n"),
    "on conflict (anzsco) do update set name = excluded.name, growth5_pct = excluded.growth5_pct, growth10_pct = excluded.growth10_pct, employed_2025k = excluded.employed_2025k, source = excluded.source, updated_at = now();",
    "",
    "commit;",
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = resolve(import.meta.dirname, "../supabase/seed.sql");
  writeFileSync(out, buildSeedSql());
  console.log(`Wrote ${out}`);
}
