/**
 * Writes supabase/seed.sql from the JSON reference data, so the database matches /data.
 * Run after editing occupations, skills or qualifications, or importing JSA data:  npm run db:seed-sql
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { earningsData, jsaOutlook, occupationData, qualificationData, skillsData } from "../src/lib/data.ts";

const q = (v: unknown) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v: unknown) => (typeof v === "number" && Number.isFinite(v) ? String(v) : "null");
const b = (v: unknown) => (v ? "true" : "false");

function insert(table: string, columns: string[], rows: string[][]): string {
  if (!rows.length) return `-- ${table}: no rows`;
  return `insert into public.${table} (${columns.join(", ")}) values\n${rows.map((r) => `  (${r.join(", ")})`).join(",\n")};`;
}

export function buildSeedSql(): string {
  const occ = occupationData.occupations;
  const quals = qualificationData.qualifications;
  const jsaSource = `${jsaOutlook.source.title} (retrieved ${jsaOutlook.source.retrieved})`;

  return [
    "-- Generated by scripts/build-seed-sql.ts. Do not edit by hand.",
    "begin;",
    "",
    "truncate public.occupation_pathways, public.occupation_skills, public.qualification_skills, public.occupations,",
    "  public.qualifications, public.skills, public.skill_clusters, public.occupation_outlook, public.occupation_earnings restart identity cascade;",
    "",
    insert("skill_clusters", ["id", "pref_label"], skillsData.clusters.map((c) => [q(c.id), q(c.prefLabel)])),
    "",
    insert(
      "skills",
      ["id", "pref_label", "broader", "type", "nst_exact_match", "asc_match"],
      skillsData.skills.map((s) => [q(s.id), q(s.prefLabel), q(s.broader), q(s.type), q(s.nstExactMatch), q(s.ascMatch)]),
    ),
    "",
    insert(
      "qualifications",
      ["id", "title", "sector", "aqf_level", "duration_years_min", "duration_years_max", "tga_code", "asced_field", "verify_code"],
      quals.map((x) => [q(x.id), q(x.title), q(x.sector), n(x.aqfLevel), n(x.durationYears[0]), n(x.durationYears[1]), q(x.tgaCode), q(x.ascedField), b(x.verifyCode)]),
    ),
    "",
    insert(
      "occupations",
      ["osca", "osca_level", "osca_unit_group", "osca_title", "title", "anzsco", "riasec", "entry_competitiveness",
        "salary_entry_min", "salary_entry_max", "salary_experienced_min", "salary_experienced_max", "qualify_years_min", "qualify_years_max", "data"],
      occ.map((o) => [
        q(o.osca), q(o.oscaLevel), q(o.oscaUnitGroup), q(o.oscaTitle), q(o.title), q(o.anzsco), q(o.riasec), q(o.entryCompetitiveness),
        n(o.salary.entry[0]), n(o.salary.entry[1]), n(o.salary.experienced[0]), n(o.salary.experienced[1]),
        n(o.timeToQualify.years[0]), n(o.timeToQualify.years[1]), `${q(JSON.stringify(o))}::jsonb`,
      ]),
    ),
    "",
    insert(
      "occupation_skills",
      ["osca", "skill_id"],
      occ.flatMap((o) => [...o.skills, ...o.coreCompetencies].map((s) => [q(o.osca), q(s)])),
    ),
    "",
    insert("qualification_skills", ["qualification_id", "skill_id"], quals.flatMap((x) => x.skills.map((s) => [q(x.id), q(s)]))),
    "",
    insert(
      "occupation_pathways",
      ["osca", "route", "qualification_id", "description", "years_min", "years_max"],
      occ.flatMap((o) => o.pathways.map((p) => [q(o.osca), q(p.route), q(p.qualification), q(p.description), n(p.years[0]), n(p.years[1])])),
    ),
    "",
    insert(
      "occupation_outlook",
      ["anzsco", "name", "growth5_pct", "growth10_pct", "employed_2025k", "source"],
      Object.entries(jsaOutlook.occupations).map(([code, f]) => [q(code), q(f.name), n(f.growth5Pct), n(f.growth10Pct), n(f.employed2025k), q(jsaSource)]),
    ),
    "",
    insert(
      "occupation_earnings",
      ["osca", "name", "median_weekly", "source"],
      Object.entries(earningsData.byOsca).map(([code, e]) => [q(code), q(e.name), n(e.medianWeekly), q(earningsData.source.title)]),
    ),
    "",
    "commit;",
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = resolve(import.meta.dirname, "../supabase/seed.sql");
  writeFileSync(out, buildSeedSql());
  console.log(`Wrote ${out}`);
}
